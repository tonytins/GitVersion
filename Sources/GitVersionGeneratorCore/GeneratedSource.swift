private func optionalString(_ value: String?) -> String {
    guard let value else { return "nil" }
    return "Optional(\(String(reflecting: value)))"
}

private func semanticVersionSource(_ version: SemanticVersion) -> String {
    """
    GitSemanticVersion(
                major: \(version.major),
                minor: \(version.minor),
                patch: \(version.patch),
                label: \(optionalString(version.label)),
                buildMetadata: \(optionalString(version.buildMetadata))
            )
    """
}

public func generatedSource(for info: RepositoryInfo) -> String {
    """
    // Generated by GitVersion. Do not edit.
    import GitVersion

    enum GitVersion {
        static let current = GitVersionInfo(
            repositoryURL: \(optionalString(info.repositoryURL)),
            branch: \(optionalString(info.branch)),
            commit: \(optionalString(info.commit)),
            fullCommit: \(optionalString(info.fullCommit)),
            commitDate: \(optionalString(info.commitDate)),
            commits: \(info.commits),
            tag: \(optionalString(info.tag)),
            baseTag: \(optionalString(info.baseTag)),
            isDirty: \(info.isDirty),
            baseVersion: \(semanticVersionSource(info.baseVersion)),
            semanticVersion: \(semanticVersionSource(info.semanticVersion))
        )

        static let major = current.major
        static let minor = current.minor
        static let patch = current.patch
        static let commit = current.commit
        static let fullCommit = current.fullCommit
        static let version = current.version
    }
    """
}
